export const labelFor = (value: string) =>
  Object.hasOwn(fieldLabels, value)
    ? fieldLabels[value]
    : value
        .replaceAll("_", " ")
        .replace(/([a-z])([A-Z])/g, "$1 $2")
        .replace(/^\w/, (value) => value.toUpperCase());


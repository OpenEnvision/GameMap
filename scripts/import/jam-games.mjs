import { applyPublishedDemos } from "../lib/round5-media.mjs";
import { readFile, writeFile, readdir, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import { loadLearningContent } from "../lib/guides/learning.mjs";
import { mergeJamReports, jamExample } from "../lib/jam-discovery.mjs";

const root = resolve(import.meta.dirname, "../..");
const args = process.argv.slice(2);
if (args.length && !(args.length === 2 && args[0] === "--reports"))
  throw new Error(
    "Usage: node scripts/import/jam-games.mjs [--reports <directory>]. Catalog load errors must never bypass existing-game deduplication.",
  );
const reportArg = args.indexOf("--reports");
const ledgerPath = resolve(root, "data/segments/jam-games.json");
const previous = await readFile(ledgerPath, "utf8")
  .then(JSON.parse)
  .catch((error) => {
    if (error.code === "ENOENT") return null;
    throw error;
  });
const reports = previous
  ? [
      {
        source: "Previously reviewed GameMap Jam games",
        accepted: previous.accepted,
        candidates: previous.candidates,
        notes: [],
      },
    ]
  : [];
if (reportArg !== -1) {
  if (!args[reportArg + 1]) throw new Error("--reports needs a directory");
  const directory = resolve(args[reportArg + 1]);
  const imported = new Set(
    previous?.accepted.map((row) => row.repository.toLowerCase()) || [],
  );
  for (const name of (await readdir(directory))
    .filter((name) => name.endsWith(".json"))
    .sort()) {
    const report = JSON.parse(await readFile(resolve(directory, name), "utf8"));
    report.accepted = report.accepted.filter(
      (row) => !imported.has(row.repository.toLowerCase()),
    );
    reports.push(report);
  }
}
if (!reports.length)
  throw new Error(
    "Supply --reports <directory> containing source-reviewed research JSON",
  );
// Fail closed: a broken or missing catalog must never erase the existing deduplication surface.
const content = await loadLearningContent();
const legacy = [...content.learningPaths, ...content.foundationPaths].filter(
  (row) => !row.id.startsWith("jam-"),
);
const research = JSON.parse(
  await readFile(
    resolve(root, "data/segments/repository-research.json"),
    "utf8",
  ),
);
const linkedResearch = research.records.filter((row) => row.game_access);
const existingRepositories = [
  ...legacy.map((row) => row.source.url),
  ...linkedResearch.map(
    (row) => `https://github.com/${row.canonical_repo || row.requested_repo}`,
  ),
].filter((url) => /^https:\/\/github.com\/[^/]+\/[^/#?]+\/?$/.test(url));
const ledger = mergeJamReports(reports, {
  checkedAt: new Date().toISOString().slice(0, 10),
  existingRepositories,
  existingBuilds: [
    ...legacy.map((row) => row.demo.url),
    ...linkedResearch.map((row) => row.game_access.url),
  ],
});
// Preserve deferred evidence and historical duplicate decisions across incremental runs.
ledger.sources = [
  ...(previous?.sources || []),
  ...ledger.sources.filter(
    (row) => row.source !== "Previously reviewed GameMap Jam games",
  ),
];
ledger.duplicates = [...(previous?.duplicates || []), ...ledger.duplicates];
const unique = (rows) => [
  ...new Map(rows.map((row) => [JSON.stringify(row), row])).values(),
];
ledger.sources = unique(ledger.sources);
ledger.duplicates = unique(ledger.duplicates);
ledger.candidates = unique(ledger.candidates);
const examples = ledger.accepted.map(jamExample);
await mkdir(resolve(root, "data/segments"), { recursive: true });
const write = async (path, body) => {
  if ((await readFile(path, "utf8").catch(() => null)) !== body)
    await writeFile(path, body);
};
await write(ledgerPath, JSON.stringify(ledger, null, 2) + "\n");
await write(
  resolve(root, "website/public/jam-discovery.json"),
  JSON.stringify(ledger, null, 2) + "\n",
);
await write(
  resolve(root, "website/src/data/jamGames.ts"),
  `// Generated by scripts/import/jam-games.mjs. Primary evidence: data/segments/jam-games.json.\nimport type { LearningPath } from './learningTypes';\n\nexport const jamGames: LearningPath[] = ${JSON.stringify(await applyPublishedDemos(examples), null, 2)};\n`,
);
console.log(
  JSON.stringify(
    {
      accepted: examples.length,
      candidates: ledger.candidates.length,
      duplicates: ledger.duplicates.length,
      verification: ledger.verification,
    },
    null,
    2,
  ),
);

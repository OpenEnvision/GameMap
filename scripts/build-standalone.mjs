import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// Classic inline scripts work with file://, unlike Vite's ES module entry.
const root = new URL('../', import.meta.url);
const result = await build({
  absWorkingDir: fileURLToPath(root),
  entryPoints: ['website/src/main.tsx'],
  outfile: 'standalone.js',
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  charset: 'utf8',
  define: {
    'process.env.NODE_ENV': '"production"',
    'import.meta.env.BASE_URL': '"./website/public/"',
  },
  external: ['/media/*'],
});

const script = result.outputFiles.find(file => file.path.endsWith('.js'))?.text;
const stylesheet = result.outputFiles.find(file => file.path.endsWith('.css'))?.text;
if (!script || !stylesheet) throw new Error('Standalone bundle is missing JavaScript or CSS.');

const css = stylesheet.replace(/url\((["']?)\/media\//g, 'url($1./website/public/media/');
const template = await readFile(new URL('website/index.html', root), 'utf8');
const entry = '<script type="module" src="/src/main.tsx"></script>';
if (!template.includes(entry)) throw new Error('Standalone HTML entry is missing.');
const html = template
  .replace('href="/favicon.svg?v=2"', 'href="./website/public/favicon.svg?v=2"')
  .replace('</head>', `<style>${css}</style>\n  </head>`)
  .replace(entry, () => `<script>${script.replace(/<\/script/gi, '<\\/script')}</script>`);

await writeFile(new URL('index.html', root), '<!-- Generated by npm run build. Edit website/src/ and website/index.html. -->\n' + html);
console.log('Built root index.html for direct file:// preview.');
